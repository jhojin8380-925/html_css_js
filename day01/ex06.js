// 관계 연산자(비교 연산자)

console.log("apple" < "pineapple"); //글자 수 비교

console.log('1' == 1); // 값이 일치하는지
console.log('1' === 1); // === 3번 써주면 타입까지 비교


console.log(undefined > 0);
console.log(undefined < 0); 

console.log(undefined == 0);
console.log(undefined === 0);

console.log(undefined == null); // == 비교시 true
console.log(undefined === null); // 타입 비교시 false





