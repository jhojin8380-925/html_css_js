// 산술 연산자
console.log(10 % 3); //10에 3을 나누고 남은 나머지 값 출력

// + 연산자
console.log(10 + 20); // 숫자 + 숫자 => 덧셈
console.log("aa" + "bb"); // 문자열 + 문자열 => 문자열 연결
console.log("hello" + 10); // 문자열 + 다른(숫자, ...) => 문자열로 연결

// 복합산술대입(누적 연산,...)
let num = 10;
num += 30;
console.log(num);
let num2 = 10;
num2 -= 5;
console.log(num2);




